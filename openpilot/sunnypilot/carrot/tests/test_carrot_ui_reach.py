"""The checked-in UI-reach table cannot drift from the code.

``docs/carrot_no_ui_switches.md`` is generated by ``audit_ui_reach.py``. Without this
test the table would rot the way its subject matter did: a switch gains or loses a
control, nothing regenerates the table, and the next audit starts from a wrong
premise. Three guards, each aimed at a way the table can lie:

  * the file matches what the scanner would emit right now (structural drift),
  * every control-path switch has a hand-written note (a row without one means
    nobody has written down what turning it on does),
  * every note belongs to a real switch (a retired param must leave the table).

Plain ``unittest.TestCase`` on purpose: the test touches files and nothing else - no
Params, no prefix, no manager cleanup - so ``OpenpilotTestCase``'s harness buys
nothing here while its import chain pulls in the hardware stack (``fcntl``), which
does not exist on a Windows checkout.
"""
import unittest

from openpilot.sunnypilot.carrot.tests.audit_ui_reach import (
  DOC_PATH, NOTES, control_switches, level_one_gaps, render, ui_entries,
)


class TestCarrotUiReach(unittest.TestCase):
  def test_the_doc_matches_the_code(self):
    with open(DOC_PATH, encoding='utf-8') as f:
      on_disk = f.read()
    built = render()
    msg = ('docs/carrot_no_ui_switches.md is stale; regenerate it with '
           + 'python3 openpilot/sunnypilot/carrot/tests/audit_ui_reach.py --write')
    self.assertEqual(on_disk, built, msg)

  def test_every_control_switch_has_a_note(self):
    missing = [name for name in control_switches() if name not in NOTES]
    msg = ('a control-path Carrot switch has no note in audit_ui_reach.NOTES; '
           + 'write down what turning it on does before listing it')
    self.assertEqual([], missing, msg)

  def test_every_note_belongs_to_a_real_switch(self):
    stale = [name for name in NOTES if name not in control_switches()]
    msg = ('NOTES entries for params no longer read on the control path; '
           + 'remove them so the table stays about live switches')
    self.assertEqual([], stale, msg)

  def test_no_everyday_knob_is_left_without_a_control(self):
    """A level-1 declaration is a promise that a person can reach it.

    Levels 2 and 3 are allowed to be scripting surfaces - they say "read the
    code before you touch this". Level 1 says the opposite, so an unreachable
    level-1 key is a contradiction the declaration itself now catches.
    """
    gaps = level_one_gaps()
    msg = 'these params declare tuning_level 1 (everyday) but no device page or panel exposes them: ' + repr(gaps)
    self.assertEqual([], gaps, msg)

  def test_the_longitudinal_source_switch_is_reachable(self):
    """The regression that started this: the switch was read by plannerd and had no control anywhere."""
    self.assertIn('CarrotLongitudinalSourceEnabled', ui_entries())


if __name__ == '__main__':
  unittest.main()
