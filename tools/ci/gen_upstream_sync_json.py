#!/usr/bin/env python3
"""Generate / refresh `upstream-sync.json` — dependency provenance manifest.

Records, without changing the submodule layout this fork relies on:
- the upstream tip this tree was last synced against (second parent of a
  merge commit, or null when HEAD is not an upstream merge), and
- every registered submodule's pinned commit AND its whole-tree hash
  (`git -C <sub> rev-parse HEAD^{tree}`).

The tree hash answers "what did we change relative to the pristine upstream
tree of <sub>" without fetching anything — opendbc/panda stop being blind
spots during upstream merges. `tools/ci/check_upstream_sync_json.py` is the
lint half: it fails when the working tree's submodule state drifts from this
manifest without a deliberate regeneration.

Usage:
  python tools/ci/gen_upstream_sync_json.py            # print to stdout
  python tools/ci/gen_upstream_sync_json.py --update   # write upstream-sync.json
"""
import argparse
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "upstream-sync.json"
UPSTREAM_URL = "https://github.com/sunnypilot/sunnypilot.git"
UPSTREAM_BRANCH = "master"


def git(*args: str, cwd: Path = ROOT, check: bool = True) -> str:
  result = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True, check=check)
  return result.stdout.strip()


def upstream_commit() -> str | None:
  parents = git("rev-list", "--parents", "-n", "1", "HEAD").split()[1:]
  if len(parents) == 2:
    # a merge commit: second parent is the upstream tip that was merged in
    return parents[1]
  return None


def submodule_paths() -> list[str]:
  out = git("config", "-f", ".gitmodules", "--get-regexp", r"submodule\..*\.path")
  paths = []
  for line in out.splitlines():
    value = line.split("=", 1)[1] if "=" in line else line.split(None, 1)[1]
    paths.append(value.strip())
  return sorted(paths)


def build() -> dict:
  submodules = {}
  for path in submodule_paths():
    cwd = ROOT / path
    if not (cwd / ".git").exists() and not (ROOT / path / "HEAD").exists():
      # not initialized; record the pinned commit from the index only
      commit = git("ls-tree", "HEAD", "--", path).split()[2] if git("ls-tree", "HEAD", "--", path) else None
      submodules[path] = {"commit": commit, "tree": None}
      continue
    commit = git("rev-parse", "HEAD", cwd=cwd)
    tree = git("rev-parse", "HEAD^{tree}", cwd=cwd)
    submodules[path] = {"commit": commit, "tree": tree}
  return {
    "_comment": "generated by tools/ci/gen_upstream_sync_json.py --update; do not hand-edit",
    "schema_version": 1,
    "generated_at": datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds"),
    "upstream": {"url": UPSTREAM_URL, "branch": UPSTREAM_BRANCH, "commit": upstream_commit()},
    "head": git("rev-parse", "HEAD"),
    "submodules": submodules,
  }


def main() -> int:
  parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
  parser.add_argument("--update", action="store_true", help="write upstream-sync.json")
  args = parser.parse_args()
  manifest = build()
  text = json.dumps(manifest, indent=2) + "\n"
  if args.update:
    MANIFEST.write_text(text)
    print(f"written: {MANIFEST}")
  else:
    print(text, end="")
  return 0


if __name__ == "__main__":
  sys.exit(main())
