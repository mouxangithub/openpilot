#!/usr/bin/env python3
"""Cereal reserved-slot contract gate (generated baseline, minimal version).

Openpilot reserves a block of Event ordinals and a file of empty structs
(cereal/custom.capnp) for forks. This fork consumes some of those slots; the
rest of the pool must stay closed. Wire-level identity in capnp is the struct
ID and the Event ordinal, not the name, so the dangerous edits are silent:
pasting a struct that reuses a reserved ID, or pointing an existing reserved
ordinal at a different struct. Neither fails at compile time.

What this gate enforces (vs the baseline JSON it generates):
1. Top-level struct set in custom.capnp is closed: additions, removals and
   renames all require a deliberate `--update` (reviewed in the PR diff).
2. Explicit struct IDs are pinned. Anonymous reserved structs must stay
   anonymous (giving one an ID changes its wire identity).
3. Every Event field that references a Custom.* type must keep both its
   ordinal and its target struct. Reserved ordinals may not be redirected,
   and a Custom.* field on a new (non-reserved) ordinal is rejected.
4. Schema file sha256s are recorded for traceability; a byte change that
   keeps the structure identical only asks for a refresh, it does not fail.

This is the machine-generated replacement for StarPilot's hand-maintained
27KB schema-policy.json — and unlike StarPilot's schema_policy.py, it is
wired into CI (cereal_validation.yaml + upstream-sync validate).

Usage:
  python tools/ci/check_capnp_schema.py            # gate (CI / pre-commit)
  python tools/ci/check_capnp_schema.py --update   # re-baseline after review
  python tools/ci/check_capnp_schema.py --print    # print current mapping
"""
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CEREAL_DIR = ROOT / "openpilot" / "cereal"
CUSTOM_CAPNP = CEREAL_DIR / "custom.capnp"
LOG_CAPNP = CEREAL_DIR / "log.capnp"
BASELINE = Path(__file__).resolve().parent / "capnp_schema_baseline.json"

# Event ordinals upstream openpilot reserves for fork custom slots
# (the "Custom: reserved for forks" block; sunnypilot consumed 107-116 and
# added 136-145). A Custom.* Event field outside this set is not part of the
# reserved pool and must go through a schema review.
RESERVED_CUSTOM_ORDINALS = set(range(107, 117)) | set(range(136, 146))

STRUCT_RE = re.compile(r"^struct (\w+)(?:\s+@(0x[0-9a-fA-F]+))?\s*\{", re.M)
# Event fields: indented `name @N :Type;` (union members sit deeper than 2 spaces)
EVENT_FIELD_RE = re.compile(r"^[ \t]+(\w+)\s+@(\d+)\s+:([^;]+);", re.M)


def sha256_of(path: Path) -> str:
  return hashlib.sha256(path.read_bytes()).hexdigest()


def parse_custom_capnp() -> dict:
  text = CUSTOM_CAPNP.read_text(encoding="utf-8")
  structs = {}
  for name, struct_id in STRUCT_RE.findall(text):
    structs[name] = struct_id if struct_id else None
  return structs


def parse_log_capnp_reserved() -> dict:
  text = LOG_CAPNP.read_text(encoding="utf-8")
  # only the Event struct's own fields (two-space indent)
  match = re.search(r"^struct Event\s*\{(.*?)\n\}", text, re.S | re.M)
  if match is None:
    raise RuntimeError("Event struct not found in log.capnp")
  body = match.group(1)
  reserved = {}
  for name, ordinal, field_type in EVENT_FIELD_RE.findall(body):
    field_type = field_type.strip()
    is_custom = field_type.startswith("Custom.")
    is_raw_reserved = name.startswith("customReservedRawData")
    if is_custom or is_raw_reserved:
      reserved[name] = {
        "ordinal": int(ordinal),
        "type": field_type,
      }
  return reserved


def build_current() -> dict:
  return {
    "_comment": "generated by tools/ci/check_capnp_schema.py --update; do not hand-edit",
    "custom.capnp": {
      "sha256": sha256_of(CUSTOM_CAPNP),
      "structs": parse_custom_capnp(),
    },
    "log.capnp": {
      "sha256": sha256_of(LOG_CAPNP),
      "event_reserved": parse_log_capnp_reserved(),
    },
    "reserved_custom_ordinals": sorted(RESERVED_CUSTOM_ORDINALS),
  }


def diff(baseline: dict, current: dict) -> list[str]:
  errors = []
  base_structs = baseline["custom.capnp"]["structs"]
  cur_structs = current["custom.capnp"]["structs"]

  for name in sorted(set(cur_structs) - set(base_structs)):
    errors.append(
      f"custom.capnp: new top-level struct '{name}' ({cur_structs[name] or 'anonymous'}) "
      f"is not in the closed reserved-slot whitelist; register it deliberately with --update after review")
  for name in sorted(set(base_structs) - set(cur_structs)):
    errors.append(f"custom.capnp: top-level struct '{name}' was removed or renamed; review and --update")
  for name in sorted(set(base_structs) & set(cur_structs)):
    if base_structs[name] != cur_structs[name]:
      errors.append(
        f"custom.capnp: struct '{name}' ID changed {base_structs[name]} -> {cur_structs[name]}; "
        f"a capnp struct ID is wire identity, not a name")

  base_res = baseline["log.capnp"]["event_reserved"]
  cur_res = current["log.capnp"]["event_reserved"]
  for field in sorted(set(cur_res) - set(base_res)):
    entry = cur_res[field]
    if entry["type"].startswith("Custom.") and entry["ordinal"] not in RESERVED_CUSTOM_ORDINALS:
      errors.append(
        f"log.capnp: Event.{field} @{entry['ordinal']} :{entry['type']} uses a NON-reserved ordinal; "
        f"Custom.* Event fields must use the upstream reserved block {sorted(RESERVED_CUSTOM_ORDINALS)}")
    else:
      errors.append(f"log.capnp: new reserved Event field '{field}' ({entry}); review and --update")
  for field in sorted(set(base_res) - set(cur_res)):
    errors.append(f"log.capnp: reserved Event field '{field}' was removed; review and --update")
  for field in sorted(set(base_res) & set(cur_res)):
    if base_res[field] != cur_res[field]:
      errors.append(
        f"log.capnp: reserved Event field '{field}' changed "
        f"{base_res[field]} -> {cur_res[field]}; reserved ordinals may not be redirected")

  return errors


def note_sha_drift(baseline: dict, current: dict) -> list[str]:
  notes = []
  for rel in ("custom.capnp", "log.capnp"):
    if baseline[rel]["sha256"] != current[rel]["sha256"]:
      structure_identical = (
        baseline[rel]["structs"] == current[rel]["structs"]
        if rel == "custom.capnp"
        else baseline[rel]["event_reserved"] == current[rel]["event_reserved"])
      if structure_identical:
        notes.append(
          f"{rel}: bytes changed but the tracked structure is identical "
          f"(comment/format edit?); run --update to refresh the recorded sha256")
  return notes


def main() -> int:
  parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
  parser.add_argument("--update", action="store_true", help="regenerate the baseline (deliberate act, review the diff)")
  parser.add_argument("--print", action="store_true", help="print the current mapping and exit")
  args = parser.parse_args()

  current = build_current()

  if args.print:
    print(json.dumps(current, indent=2))
    return 0

  if args.update:
    old = json.loads(BASELINE.read_text()) if BASELINE.exists() else None
    BASELINE.write_text(json.dumps(current, indent=2) + "\n")
    print(f"baseline written: {BASELINE}")
    if old is not None:
      for error in diff(old, current):
        print(f"  CHANGED: {error}")
    return 0

  if not BASELINE.exists():
    print(f"baseline missing: {BASELINE}; run with --update to generate", file=sys.stderr)
    return 1

  baseline = json.loads(BASELINE.read_text())
  errors = diff(baseline, current)
  for note in note_sha_drift(baseline, current):
    print(f"note: {note}")
  for error in errors:
    print(f"::error::{error}")
  if errors:
    print(f"\ncereal reserved-slot gate FAILED with {len(errors)} violation(s)")
    return 1
  print("cereal reserved-slot gate OK "
        f"({len(current['custom.capnp']['structs'])} structs, "
        f"{len(current['log.capnp']['event_reserved'])} reserved Event fields)")
  return 0


if __name__ == "__main__":
  sys.exit(main())
